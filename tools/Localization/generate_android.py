"""Generate the dependency-free Android catalogue from the shared UTF-8 JSON files."""
from pathlib import Path
import json,sys
root=Path(__file__).resolve().parents[2]
languages=['de','ru','fr','es']
data={c:json.loads((root/'locales'/f'{c}.json').read_text(encoding='utf-8')) for c in languages}
q=lambda s:json.dumps(s,ensure_ascii=False)
lines=['// Generated by tools/Localization/generate_android.py; edit locales/*.json instead.',
'package pl.proszczok.stroik;', 'import java.util.*;', 'final class Translations {',
'  static final String[] CODES = {"pl", "en", "de", "ru", "fr", "es"};',
'  static final String[] NAMES = {"Polski", "English", "Deutsch", "Русский", "Français", "Español"};',
'  private static final Map<String,String[]> TEXT = new HashMap<>();', '  static {']
for key in sorted(data['de']):
 lines.append('    TEXT.put('+q(key)+', new String[]{'+','.join(q(data[c][key]) for c in languages)+'});')
lines+=['  }', '  static boolean supported(String code) { return Arrays.asList(CODES).contains(code); }',
'  static String get(String code, String pl, String en) {',
'    if (code.equals("pl")) return pl;',
'    int index = Arrays.asList(CODES).indexOf(code)-2;',
'    String[] values=TEXT.get(en);',
'    return index>=0 && values!=null ? values[index] : en;', '  }', '}']
target=root/'android/app/src/main/java/pl/proszczok/stroik/Translations.java'
generated='\n'.join(lines)+'\n'
if '--check' in sys.argv:
 assert target.read_text(encoding='utf-8')==generated,'Translations.java differs from locales/*.json; regenerate it.'
else:target.write_text(generated,encoding='utf-8')
